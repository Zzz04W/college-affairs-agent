# -*- coding: utf-8 -*-
"""从 01_素材/咨询群聊记录_原始_含个人信息.csv 脱敏，生成 01_输出/语料库/咨询问题频次表.md。
只保留「问题类型 + 出现次数 + 对应条款」，删除姓名/学号/手机号/时间等个人信息。
"""
import csv, os, re
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "01_素材", "咨询群聊记录_原始_含个人信息.csv")

RULES = [
    ("补考（申请/次数/时间）", ["补考"]),
    ("缓考（材料/成绩单/缺考）", ["缓考"]),
    ("重修（学费/次数）", ["重修"]),
    ("成绩复核（费用/看卷/时限）", ["复核"]),
    ("奖助学金（条件/金额/兼得/发放/处分影响）", ["奖学金", "助学金"]),
    ("报修（宿舍/教室·渠道/时限/赔偿/大件）", ["报修", "漏水", "门锁", "空调", "投影", "音响"]),
    ("其他教务（成绩单/学籍/转专业/休学/选课，超出六类）", ["成绩单", "学籍", "转专业", "休学", "选课", "退课"]),
    ("资料未收录（交换生/校园卡等）", ["交换生", "校园卡", "一卡通"]),
]

def classify(q):
    for name, kws in RULES:
        if any(k in q for k in kws):
            return name
    return "其他（未归类）"

counter = Counter()
with open(src, encoding="utf-8-sig") as f:
    for row in csv.DictReader(f):
        q = row.get("问题原文", "")
        counter[classify(q)] += 1

lines = ["# 咨询问题频次表（脱敏后）", "",
         "> 来源：01_素材/咨询群聊记录_原始_含个人信息.csv（30 条真实口径提问）。",
         "> 脱敏说明：已删除姓名、学号、手机号、具体提问时间与来源渠道；仅保留「问题类型 + 出现次数」。",
         "> 用途：提炼学生真实口语问法，作为系统提示词补同义表述、检索关键词的依据。", "",
         "| 排名 | 问题类型 | 出现次数 | 对应条款（现行有效） |",
         "| --- | --- | --- | --- |"]
clause_map = {
    "补考（申请/次数/时间）": "教学管理制度 第四条／第五条／第六条第（三）项",
    "缓考（材料/成绩单/缺考）": "教学管理制度 第八条／第九条／第十条／第十一条",
    "重修（学费/次数）": "教学管理制度 第十四条／第十五条",
    "成绩复核（费用/看卷/时限）": "教学管理制度 第十六条／第十七条",
    "奖助学金（条件/金额/兼得/发放/处分影响）": "奖助学金办法 第五／七／十／十一条",
    "报修（宿舍/教室·渠道/时限/赔偿/大件）": "宿舍报修办法 第三／四／五条；教室多媒体流程 第二／三条",
    "其他教务（成绩单/学籍/转专业/休学/选课，超出六类）": "资料未收录（应拒答并给替代路径）",
    "资料未收录（交换生/校园卡等）": "资料未收录（应拒答并给替代路径）",
}
for i, (name, n) in enumerate(counter.most_common(), 1):
    lines.append(f"| {i} | {name} | {n} | {clause_map.get(name,'—')} |")
lines += ["", f"**合计**：{sum(counter.values())} 条。其中「其他教务」与「资料未收录」两类共 "
          f"{counter.get('其他教务（成绩单/学籍/转专业/休学/选课，超出六类）',0)+counter.get('资料未收录（交换生/校园卡等）',0)} 条，"
          "属本次六类范围之外，验证智能体须正确拒答。", ""]

out = os.path.join(ROOT, "01_输出", "语料库", "咨询问题频次表.md")
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print("written:", out)
print("\n".join(lines))

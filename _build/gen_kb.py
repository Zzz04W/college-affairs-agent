# 3) 检索算法（与 index.html 保持一致）
# ---------------------------------------------------------------------------
def score_entry(e, q):
    s = sum(1 for kw in e["keywords"] if kw in q)
    return s * e.get("weight", 1.0)

def answer(q):
    # 1) 安全越界优先
    for s in SAFETY:
        if any(kw in q for kw in s["keywords"]):
            return dict(mode="safety", type=s["type"], conclusion=s["conclusion"],
                        evidence=s["text"], nextstep=s["nextstep"], ids=[])
    # 2) 检索
    scored = [(score_entry(e, q), e) for e in KB]
    scored = [(s, e) for s, e in scored if s >= 2.0]
    scored.sort(key=lambda x: -x[0])
    if not scored:
        return dict(mode="fallback", **FALLBACK, type=None, ids=[])
    seen = set(); entries = []
    for s, e in scored:
        if e["id"] in seen:
            continue
        seen.add(e["id"]); entries.append(e)
    return dict(mode="kb", entries=entries, ids=[e["id"] for e in entries])

